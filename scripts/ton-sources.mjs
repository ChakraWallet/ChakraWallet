// Generates src/shared/ton/templateSources.js from src/shared/ton/sources/ (see its README): the FunC sources of the
// TON templates, shown in the app before a contract is created. The standard library is left out (it is the
// standard one, and large). Usage: node scripts/ton-sources.mjs
import fs from 'node:fs';
import path from 'node:path';

// the project folder: run from it (npm scripts and the unit tests, which are bundled elsewhere, do)
const ROOT = process.cwd();
export const SRC = path.join(ROOT, 'src/shared/ton/sources');
export const TEMPLATE_SOURCES = {
  JETTON_MINTER: { dir: 'jetton', main: 'jetton-minter.fc', repo: 'github.com/ton-blockchain/minter-contract' },
  JETTON_WALLET: { dir: 'jetton', main: 'jetton-wallet.fc', repo: 'github.com/ton-blockchain/minter-contract' },
  NFT_COLLECTION: { dir: 'nft', main: 'nft-collection-editable.fc', repo: 'github.com/ton-blockchain/token-contract' },
  NFT_ITEM: { dir: 'nft', main: 'nft-item.fc', repo: 'github.com/ton-blockchain/token-contract' },
};
// the files compiled with each main file, in order (nft: no #include, the build passes them before)
export const BUILD = {
  jetton: (main) => [main],
  nft: (main) => ['stdlib.fc', 'params.fc', 'op-codes.fc', main],
};

/** Files of a folder (relative paths), .fc only. */
export function filesOf(dir) {
  const out = {};
  const walk = (d) => {
    for (const e of fs.readdirSync(path.join(SRC, dir, d), { withFileTypes: true })) {
      const rel = path.posix.join(d, e.name);
      if (e.isDirectory()) walk(rel);
      else if (e.name.endsWith('.fc')) out[rel] = fs.readFileSync(path.join(SRC, dir, rel), 'utf8');
    }
  };
  walk('');
  return out;
}

export function generate() {
  const folders = {};
  for (const dir of new Set(Object.values(TEMPLATE_SOURCES).map((s) => s.dir))) {
    folders[dir] = Object.fromEntries(Object.entries(filesOf(dir)).filter(([f]) => !/(^|\/)stdlib\.fc$/.test(f)));
  }
  return `// GENERATED by scripts/ton-sources.mjs from src/shared/ton/sources/ - do not edit.
// FunC sources of the TON templates (official contracts; they compile to the code hashes pinned in templates.js,
// checked by tests/tonsources.test.js). The standard library (stdlib.fc) is left out.
export const TEMPLATE_SOURCES = ${JSON.stringify(TEMPLATE_SOURCES, null, 2)};
export const SOURCE_FILES = ${JSON.stringify(folders, null, 2)};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  fs.writeFileSync(path.join(ROOT, 'src/shared/ton/templateSources.js'), generate());
  console.log('src/shared/ton/templateSources.js written');
}
