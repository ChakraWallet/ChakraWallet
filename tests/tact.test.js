// Tact studio: compile with the browser entry of the compiler (as the worker does), then check that the init data and
// the message bodies the app builds from the ABI + allocations are identical to the ones of the TypeScript bindings
// Tact generates for the same contract.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import * as esbuild from 'esbuild';
import { beginCell, Cell, contractAddress } from '@ton/core';
import { compileTactProject } from '../src/shared/ton/tactCompile.js';
import { tactInitData, tactMessageBody, tactStackArg, fieldKind, emptyOf, tactReceivers, DEFAULT_TACT } from '../src/shared/ton/tact.js';
import { stateInitB64 } from '../src/shared/ton/templates.js';

const SRC = `
struct Point { x: Int as int16; y: Int as int16; }
message(0x12345678) Configure {
    owner: Address;
    label: String;
    limit: Int as coins;
    point: Point;
    note: Cell?;
    flag: Bool;
    big: Int;
    other: Address?;
    tag: Int? as uint8;
}
contract Rich {
    owner: Address;
    id: Int as uint32;
    name: String;
    amount: Int as coins;
    flag: Bool;
    note: Cell?;
    maybeAddr: Address?;
    big: Int;
    big2: Int;
    big3: Int;
    big4: Int;
    p: Point;

    init(owner: Address, id: Int as uint32, name: String, amount: Int as coins, flag: Bool, note: Cell?, maybeAddr: Address?, big: Int, big2: Int, big3: Int, big4: Int, p: Point) {
        self.owner = owner; self.id = id; self.name = name; self.amount = amount; self.flag = flag;
        self.note = note; self.maybeAddr = maybeAddr; self.big = big; self.big2 = big2; self.big3 = big3; self.big4 = big4; self.p = p;
    }
    receive() {}
    receive(msg: Configure) { self.owner = msg.owner; }
    receive("ping") {}
    get fun id(): Int { return self.id; }
    get fun named(n: String): Bool { return n == self.name; }
}`;

const OWNER = '0:' + '11'.repeat(32), OTHER = 'EQCxE6mUtQJKFnGfaROTKOt1lZbDiiX1kCixRv7Nw2Id_sDs';
const NOTE = beginCell().storeUint(77, 16).endCell();

let compiled;
async function build() {
  if (!compiled) compiled = await compileTactProject({ files: { 'main.tact': SRC }, main: 'main.tact', bindings: true });
  return compiled;
}

/** The TypeScript bindings generated by Tact, transpiled and loaded with the same @ton/core as this test. */
async function bindings(ts) {
  const require = createRequire(import.meta.url);
  const core = pathToFileURL(require.resolve('@ton/core')).href;
  const js = (await esbuild.transform(ts, { loader: 'ts', format: 'esm' })).code.replace(/from\s+["']@ton\/core["']/g, `from '${core}'`);
  const file = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'chakra-tact-')), 'bindings.mjs');
  fs.writeFileSync(file, js);
  return { mod: await import(pathToFileURL(file).href), core: await import(core) };
}

test('Tact: compiles with the browser entry, errors with file and line', async () => {
  const r = await build();
  assert.equal(r.ok, true, JSON.stringify(r.errors));
  const c = r.contracts.find((x) => x.name === 'Rich');
  assert.ok(c);
  assert.ok(Cell.fromBase64(c.code));
  assert.deepEqual(c.abi.getters.map((g) => g.name).sort(), ['id', 'named']);
  assert.deepEqual(tactReceivers(c.abi).map((x) => x.kind).sort(), ['empty', 'text', 'typed']);
  assert.equal(c.types.Configure.header, 0x12345678);
  assert.ok(c.init.allocation.next, 'init arguments spill into a second cell');

  const bad = await compileTactProject({ files: { 'main.tact': 'contract X {\n  get fun a(): Int { return ; }\n}' }, main: 'main.tact' });
  assert.equal(bad.ok, false);
  assert.equal(bad.errors[0].file, 'main.tact');
  assert.equal(bad.errors[0].line, 2);

  const def = await compileTactProject({ files: { 'main.tact': DEFAULT_TACT }, main: 'main.tact' });
  assert.equal(def.ok, true, JSON.stringify(def.errors));
});

test('Tact: init data and address are the same as the bindings', async () => {
  const c = (await build()).contracts.find((x) => x.name === 'Rich');
  const { mod, core } = await bindings(c.bindings);
  const big = (1n << 200n) + 12345n;
  for (const [note, maybeAddr] of [[null, null], [NOTE, OTHER]]) {
    const theirs = await mod.Rich.fromInit(
      core.Address.parse(OWNER), 7n, 'hello Tact', 1_500_000_000n, true, note ? core.Cell.fromBase64(note.toBoc().toString('base64')) : null,
      maybeAddr ? core.Address.parse(maybeAddr) : null, big, -big, 1n, -1n, { $$type: 'Point', x: -3n, y: 4n },
    );
    const values = {
      owner: OWNER, id: '7', name: 'hello Tact', amount: { v: '1.5', unit: 9 }, flag: true, note: note ? note.toBoc().toString('base64') : '',
      maybeAddr: maybeAddr || '', big: big.toString(), big2: (-big).toString(), big3: '1', big4: '-1', p: { x: '-3', y: '4' },
    };
    const data = tactInitData(c.init, values, c.types);
    assert.equal(data.hash().toString('hex'), theirs.init.data.hash().toString('hex'));
    const ours = contractAddress(0, { code: Cell.fromBase64(c.code), data });
    assert.equal(ours.toRawString(), theirs.address.toRawString());
    assert.ok(stateInitB64({ code: Cell.fromBase64(c.code), data }));
  }
});

test('Tact: typed message bodies are the same as the bindings', async () => {
  const c = (await build()).contracts.find((x) => x.name === 'Rich');
  const { mod, core } = await bindings(c.bindings);
  const msg = { $$type: 'Configure', owner: core.Address.parse(OTHER), label: 'L'.repeat(140), limit: 42n, point: { $$type: 'Point', x: 1n, y: -2n }, note: null, flag: false, big: -99n, other: null, tag: 200n };
  const theirs = core.beginCell().store(mod.storeConfigure(msg)).endCell();
  const ours = tactMessageBody('Configure', { owner: OTHER, label: 'L'.repeat(140), limit: { v: '42', unit: 0 }, point: { x: '1', y: '-2' }, note: '', flag: false, big: '-99', other: '', tag: '200' }, c.types);
  assert.equal(ours.hash().toString('hex'), theirs.hash().toString('hex'));
  const t2 = core.beginCell().store(mod.storeConfigure({ ...msg, note: core.Cell.fromBase64(NOTE.toBoc().toString('base64')), other: core.Address.parse(OWNER), tag: null })).endCell();
  const o2 = tactMessageBody('Configure', { owner: OTHER, label: 'L'.repeat(140), limit: '42', point: { x: '1', y: '-2' }, note: NOTE.toBoc().toString('base64'), flag: false, big: '-99', other: OWNER, tag: '' }, c.types);
  assert.equal(o2.hash().toString('hex'), t2.hash().toString('hex'));
});

test('Tact: forms and getter arguments', async () => {
  const c = (await build()).contracts.find((x) => x.name === 'Rich');
  const cfg = c.abi.types.find((x) => x.name === 'Configure');
  const kinds = Object.fromEntries(cfg.fields.map((f) => [f.name, fieldKind(f.type, c.types).kind]));
  assert.deepEqual(kinds, { owner: 'address', label: 'string', limit: 'coins', point: 'struct', note: 'cell', flag: 'bool', big: 'int', other: 'address', tag: 'uint' });
  assert.deepEqual(emptyOf(cfg.fields.find((f) => f.name === 'point').type, c.types, c.abi.types), { x: '', y: '' });
  const named = c.abi.getters.find((g) => g.name === 'named');
  const arg = tactStackArg(named.arguments[0].type, 'hello');
  assert.equal(arg.type, 'slice');
  assert.equal(Cell.fromBase64(arg.value).beginParse().loadStringTail(), 'hello');
  assert.deepEqual(tactStackArg({ kind: 'simple', type: 'bool' }, true), { type: 'int', value: '-1' });
});
